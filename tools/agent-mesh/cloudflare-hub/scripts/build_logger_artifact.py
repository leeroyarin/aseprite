"""Generate/check the exact downloadable standalone script; no deployment/network."""
from pathlib import Path
import json
import sys
root=Path(__file__).resolve().parents[1]
source=(root/'sidecar/hub_command_log.py').read_text(encoding='utf-8')
expected='// Generated by scripts/build_logger_artifact.py; do not edit by hand.\nexport const LOGGER_SOURCE = '+json.dumps(source,ensure_ascii=True)+';\n'
target=root/'src/logger-artifact.ts'
if '--check' in sys.argv:
    if not target.exists() or target.read_text(encoding='utf-8')!=expected:
        raise SystemExit('Logger artifact is stale; run npm run build:logger')
else:
    target.write_text(expected,encoding='utf-8',newline='\n')
